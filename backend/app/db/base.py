"""The declarative base every ORM model inherits from, plus shared column mixins.

Models live in their modules (``app/modules/<module>/models.py``); ``app/db/models.py`` imports them all so
``Base.metadata`` is complete for Alembic autogenerate and ``alembic check``.
"""

import os
import time
import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint names, so migrations can reference (and drop) them reliably.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


def uuid7() -> uuid.UUID:
    """RFC 9562 UUIDv7: 48-bit Unix milliseconds, then 74 random bits.

    Time-ordered, so primary-key indexes stay compact and inserts stay local. The creation time is readable
    from the id, so ids are never secrets.
    """
    ms = time.time_ns() // 1_000_000
    rand = int.from_bytes(os.urandom(10), "big")  # 80 bits; 74 are used
    value = (
        (ms & 0xFFFF_FFFF_FFFF) << 80
        | 0x7 << 76  # version
        | (rand >> 68) << 64  # rand_a: 12 bits
        | 0b10 << 62  # RFC 9562 variant
        | rand & ((1 << 62) - 1)  # rand_b: 62 bits
    )
    return uuid.UUID(int=value)


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKey:
    """UUIDv7 generated by the application; ``gen_random_uuid()`` covers raw SQL inserts."""

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid7, server_default=text("gen_random_uuid()")
    )


class Timestamps:
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    # Maintained by the ORM on every UPDATE it issues (raw SQL updates must set it themselves).
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


def check_in(column: str, values: tuple[str, ...]) -> str:
    """SQL for a CHECK that ``column`` is one of ``values`` (used instead of PostgreSQL enum types)."""
    return f"{column} IN ({', '.join(repr(v) for v in values)})"
