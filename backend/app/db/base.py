"""The declarative base every ORM model inherits from, plus shared column mixins.

Models live in their modules (``app/modules/<module>/models.py``); ``app/db/models.py`` imports them all so
``Base.metadata`` is complete for Alembic autogenerate and ``alembic check``.
"""

import hashlib
import os
import threading
import time
import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint names, so migrations can reference (and drop) them reliably.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


_uuid7_lock = threading.Lock()
_uuid7_last = (0, 0)  # (milliseconds, 12-bit counter) of the previous id


def uuid7() -> uuid.UUID:
    """RFC 9562 UUIDv7: 48-bit Unix milliseconds, a 12-bit counter, then 62 random bits.

    Time-ordered, so primary-key indexes stay compact and inserts stay local. Monotonic within the process
    (RFC 9562 §6.2, method 1): ids generated in the same millisecond increment the counter, so ordering by id
    reproduces creation order. Member listings rely on this. The creation time is readable from the id, so
    ids are never secrets.
    """
    global _uuid7_last
    with _uuid7_lock:
        ms = time.time_ns() // 1_000_000
        last_ms, last_counter = _uuid7_last
        if ms > last_ms:
            counter = int.from_bytes(os.urandom(2), "big") & 0x7FF  # random start, leaving headroom
        else:
            ms, counter = last_ms, last_counter + 1
            if counter > 0xFFF:  # counter exhausted within one millisecond: borrow the next one
                ms, counter = last_ms + 1, 0
        _uuid7_last = (ms, counter)
    rand_b = int.from_bytes(os.urandom(8), "big") & ((1 << 62) - 1)
    value = (ms & 0xFFFF_FFFF_FFFF) << 80 | 0x7 << 76 | counter << 64 | 0b10 << 62 | rand_b
    return uuid.UUID(int=value)


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def deterministic_uuid7(at: datetime, label: str) -> uuid.UUID:
    """A valid UUIDv7 that is the same every time for the same (time, label): for seed rows that must be idempotent.

    The 48-bit timestamp is ``at`` in Unix milliseconds (so it sorts with real events of that time); the remaining
    74 bits come from SHA-256 of the label. Not random, so never use it for anything secret or user-facing.
    """
    ms = int(at.timestamp() * 1000)
    digest = int.from_bytes(hashlib.sha256(label.encode()).digest()[:10], "big")
    value = (ms & 0xFFFF_FFFF_FFFF) << 80 | 0x7 << 76 | (digest >> 68) << 64 | 0b10 << 62 | digest & ((1 << 62) - 1)
    return uuid.UUID(int=value)


class UUIDPrimaryKey:
    """UUIDv7, always generated by the application. There is deliberately no database default: an insert without
    an id fails instead of silently getting a different (e.g. v4) id."""

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid7)


class Timestamps:
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    # Maintained by the ORM on every UPDATE it issues (raw SQL updates must set it themselves).
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


def check_in(column: str, values: tuple[str, ...]) -> str:
    """SQL for a CHECK that ``column`` is one of ``values`` (used instead of PostgreSQL enum types)."""
    return f"{column} IN ({', '.join(repr(v) for v in values)})"
